// 6. Structure Return Demotion (sret)
// ============================================================

void sretDemotionExample() {
  // Problem: A function returns a large struct that doesn't fit in registers.
  //   struct Big { int field[20]; };
  //   Big callee();

  // Without sret:
  //   Big callee() { ... return result; }
  // The compiler must fit Big into registers -> impossible.

  // With sret demotion:
  //   void callee(Big* sret_ptr) { ... *sret_ptr = result; }
  // The caller allocates stack space and passes a pointer.
  // The callee writes the return value through the pointer.

  // How to check (in TargetLowering or CallLowering):
  //   bool CanLowerReturn = CCInfo.CheckReturn(Outs, CC_XXX);
  //   if (!CanLowerReturn) {
  //     // Demote: add a pointer parameter at position 0
  //     // The pointer gets the sret attribute in LLVM IR
  //     insertSRetIncomingArgument(...);
  //   }

  // The sret pointer is treated as an extra formal argument
  // at index 0 on the callee side.
}

