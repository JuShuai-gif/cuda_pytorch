// ============================================================
// 1. Calling Convention infrastructure (simulated)
// ============================================================

// A calling convention is identified by an ID.
struct CallingConv {
  enum ID {
    C,
    Fast,
    Cold,
    // ... many more
  };
};

// Flags carried by arguments (e.g., signext, zeroext, inreg, etc.)
struct ArgFlagsTy {
  bool isSExt()  const { return SExt; }
  bool isZExt()  const { return ZExt; }
  bool isInReg() const { return InReg; }
  bool SExt = false, ZExt = false, InReg = false;
  // ... many more flags
};

// Value type (simulated MVT)
struct MVT {
  unsigned Size;
  bool isInteger() const { return true; }
  unsigned getSizeInBits() const { return Size; }
  static MVT i8()  { return {8}; }
  static MVT i16() { return {16}; }
  static MVT i32() { return {32}; }
  static MVT f32() { return {32}; }
};

// ============================================================
// 2. CCValAssign - the "identity card" of a lowered value
// ============================================================

struct CCValAssign {
  enum LocInfo {
    Full,   // No transformation needed (ValVT == LocVT)
    SExt,   // Sign-extend from ValVT to LocVT
    ZExt,   // Zero-extend from ValVT to LocVT
    AExt,   // Any-extend (don't care about high bits)
    BCvt,   // Bit-convert
    Indirect, // Passed indirectly (by address)
  };

  // Where does this value live?
  bool isRegLoc() const { return IsRegister; }
  bool isMemLoc() const { return !IsRegister; }

  // Get the location
  unsigned getLocReg()      const { return Loc; }  // Physical register
  unsigned getLocMemOffset() const { return Loc; }   // Stack offset

  // Original type (as declared in LLVM IR)
  MVT getValVT() const { return ValVT; }

  // Actual type (as stored in the physical location)
  MVT getLocVT() const { return LocVT; }

  // How to convert between ValVT and LocVT
  LocInfo getLocInfo() const { return Info; }

  // Internal fields
  bool IsRegister;
  unsigned Loc;       // Register number or memory offset
  MVT ValVT;          // Original type
  MVT LocVT;          // Type in the location
  LocInfo Info;       // Extension/conversion kind
};

// ============================================================
// 3. CCAssignFn - generated by TableGen (gen-callingconv)
// ============================================================

// This is the signature of the function generated by TableGen:
//   bool CC_XXX(unsigned ValNo, MVT ValVT, MVT LocVT,
//               CCValAssign::LocInfo LocInfo, ArgFlagsTy Flags,
//               CCState &State);
using CCAssignFn = std::function<bool(unsigned, MVT, MVT,
                                       CCValAssign::LocInfo,
                                       ArgFlagsTy, /*CCState&*/ void*)>;

// Simulated TableGen-generated calling convention function.
// This mimics what "gen-callingconv" produces.
bool CC_H2BLB_Common(unsigned ValNo, MVT ValVT, MVT LocVT,
                      CCValAssign::LocInfo LocInfo,
                      ArgFlagsTy Flags, void *State) {
  // In real code, this is generated from your CallingConv TableGen record.
  // The body evaluates CCAction records in order:
  //
  //   CCIfType<[v2i16], CCBitConvertToType<i32>>,
  //   CCIfType<[i16,f16], CCAssignToReg<[R1, R2, R3]>>,
  //   CCIfType<[i32,f32], CCAssignToReg<[D1]>>,
  //   CCAssignToStack<2, 2>
  //
  // For simulation, return true to indicate the location was assigned.
  (void)ValNo; (void)ValVT; (void)LocVT;
  (void)LocInfo; (void)Flags; (void)State;
  return true;
}

// ============================================================
// 4. CCState - manages the state of ABI lowering
// ============================================================

class CCState {
  std::vector<CCValAssign> &Locs;
  CallingConv::ID CallConv;
  bool IsVarArg;

public:
  CCState(CallingConv::ID CC, bool VarArg, std::vector<CCValAssign> &Locations)
    : Locs(Locations), CallConv(CC), IsVarArg(VarArg) {}

  // Analyze formal arguments: determines where each incoming argument lives.
  // This is called from LowerFormalArguments on the callee side.
  bool AnalyzeFormalArguments(
      const std::vector<std::pair<MVT, ArgFlagsTy>> &Ins,
      CCAssignFn Fn) {
    Locs.clear();
    for (size_t i = 0; i < Ins.size(); ++i) {
      MVT VT = Ins[i].first;
      ArgFlagsTy Flags = Ins[i].second;
      // The TableGen function fills in the location.
      // We simulate: if VT.getSizeInBits() <= 16, use register; else use stack.
      CCValAssign VA;
      if (VT.getSizeInBits() <= 16) {
        VA.IsRegister = true;
        VA.Loc = static_cast<unsigned>(i + 1); // R1, R2, R3...
        VA.ValVT = VT;
        VA.LocVT = MVT::i16(); // Promote to register width
        VA.Info = (VT.getSizeInBits() < 16) ? CCValAssign::SExt : CCValAssign::Full;
      } else {
        VA.IsRegister = false;
        VA.Loc = static_cast<unsigned>(i * 4); // Stack offset
        VA.ValVT = VT;
        VA.LocVT = VT;
        VA.Info = CCValAssign::Full;
      }
      Locs.push_back(VA);
    }
    return true;
  }

  // Analyze return values: determines where each return value lives.
  bool AnalyzeReturn(const std::vector<std::pair<MVT, ArgFlagsTy>> &Outs,
                     CCAssignFn Fn) {
    // Similar to AnalyzeFormalArguments but for outgoing return values.
    Locs.clear();
    for (size_t i = 0; i < Outs.size(); ++i) {
      CCValAssign VA;
      VA.IsRegister = true;
      VA.Loc = static_cast<unsigned>(100 + i); // Return registers
      VA.ValVT = Outs[i].first;
      VA.LocVT = Outs[i].first;
      VA.Info = CCValAssign::Full;
      Locs.push_back(VA);
    }
    return true;
  }

  // Check if a return value fits in registers (for sret demotion decision).
  bool CheckReturn(const std::vector<std::pair<MVT, ArgFlagsTy>> &Outs,
                   CCAssignFn Fn) {
    // Returns true if the return value can be passed in registers directly.
    // If the structure is too large, returns false -> sret demotion.
    size_t totalSize = 0;
    for (auto &Out : Outs)
      totalSize += Out.first.getSizeInBits();
    return totalSize <= 64; // Assume max 64 bits in registers
  }

  const std::vector<CCValAssign> &getLocs() const { return Locs; }
};

