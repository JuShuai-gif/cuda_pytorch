// 5. ABI lowering example: LowerFormalArguments (callee side)
// ============================================================

// Simulated "MachineFunction" and related helpers
struct MachineFunction {
  std::vector<unsigned> LiveIns; // Physical registers that are live-in
};

// In SDISel, LowerFormalArguments is implemented in XXXTargetLowering.
// It uses CCState to determine locations, then creates SDNodes.

void lowerFormalArgumentsExample() {
  // Input: the function being lowered
  //   define i16 @foo(i16 %a, i8 %b)

  // Step 1: Gather the input argument descriptions
  std::vector<std::pair<MVT, ArgFlagsTy>> Ins;
  Ins.push_back({MVT::i16(), ArgFlagsTy{}}); // %a: i16
  Ins.push_back({MVT::i8(),  ArgFlagsTy{}}); // %b: i8

  // Step 2: Create CCState and analyze
  std::vector<CCValAssign> ArgLocs;
  CCState CCInfo(CallingConv::C, false, ArgLocs);
  CCInfo.AnalyzeFormalArguments(Ins, CC_H2BLB_Common);

  // Step 3: For each CCValAssign, generate the right sequence
  for (size_t i = 0; i < ArgLocs.size(); ++i) {
    const CCValAssign &VA = ArgLocs[i];

    if (VA.isRegLoc()) {
      // Argument in a register.
      unsigned PhysReg = VA.getLocReg();
      MVT RegVT = VA.getLocVT();

      // In SDISel:
      //   Register VReg = RegInfo.createVirtualRegister(DstRC);
      //   RegInfo.addLiveIn(PhysReg, VReg);
      //   SDValue ArgVal = DAG.getCopyFromReg(Chain, DL, VReg, RegVT);
      //   InVals.push_back(ArgVal);

      // In GlobalISel:
      //   Register VReg = MRI.createGenericVirtualRegister(LLT::scalar(RegVT.getSizeInBits()));
      //   MIRBuilder.buildCopy(VReg, PhysReg); // simplified

      // Handle extension if ValVT != LocVT
      if (VA.getLocInfo() == CCValAssign::SExt) {
        // Create a sign-extend instruction from LocVT to ValVT
        // In SDISel: DAG.getNode(ISD::SIGN_EXTEND, ...)
        // In GlobalISel: MIRBuilder.buildSExt(...)
      }

      // Record the mapping: formal argument i -> virtual register VReg
      (void)PhysReg; (void)RegVT;
    } else {
      // Argument on the stack.
      unsigned Offset = VA.getLocMemOffset();
      unsigned Size   = VA.getValVT().getSizeInBits() / 8;

      // Create a stack slot:
      //   int FrameIdx = MFI.CreateFixedObject(Size, Offset, /*Immutable=*/true);
      //   SDValue FrameNode = DAG.getFrameIndex(FrameIdx, PtrTy);
      //   MachinePointerInfo PtrInfo = MachinePointerInfo::getFixedStack(MF, FrameIdx);
      //   SDValue Load = DAG.getLoad(ValVT, DL, Chain, FrameNode, PtrInfo);

      (void)Offset; (void)Size;
    }
  }
}

