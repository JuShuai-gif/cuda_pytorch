#pragma once

#include <cstddef>
#include <vector>
#include <cstdint>

// ============================================================================
// 用于伪共享演示的卡尔曼滤波跟踪状态。
// 每个跟踪记录跟踪一个目标的位置、速度、加速度，
// 使用 6 状态滤波器: [x, y, vx, vy, ax, ay] 和 6x6 协方差矩阵。
// ============================================================================
struct KalmanTrack {
    float state[6]; // x, y, vx, vy, ax, ay
    float cov[36];  // 6x6 协方差矩阵 (行主序)
    int track_id;
    int64_t last_update_us;

    void predict(float dt);
};

// ============================================================================
// 伪共享: 8 个卡尔曼跟踪分别放置在相同缓存行与独立缓存行上。
// 线程在独立的跟踪上并发运行卡尔曼预测。
// ============================================================================
void demo_false_sharing();

// ============================================================================
// 缓存抖动: 640x480x3 图像块处理 (3x3 模糊)
// 比较行主序遍历与列主序遍历。
// ============================================================================
void demo_cache_thrashing();

// ============================================================================
// 工具: 估算 CPU 缓存行大小
// ============================================================================
int estimate_cache_line_size();
