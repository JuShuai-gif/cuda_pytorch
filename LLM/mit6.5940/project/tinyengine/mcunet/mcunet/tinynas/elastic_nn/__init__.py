# =============================================================================
# elastic_nn 包初始化文件
# elastic_nn（弹性神经网络）是 OFA (Once for All) 框架的核心组件。
#
# OFA 的核心思想是：一次性训练一个"超网络"（Super-Net），
# 该超网络包含多种子网络配置（不同的宽度、深度、卷积核大小、扩展比等），
# 然后可以直接从中采样出特定大小的子网络用于部署，无需重新训练。
#
# 这个包提供了构建弹性（动态）神经网络所需的全部模块：
#   - dynamic_op.py:      基础动态算子（可分离卷积、点卷积、全连接、BN、SE）
#   - dynamic_layers.py:  高级动态层（MBConv、普通卷积、全连接层）
#   - networks/:           基于动态层构建的完整超网络架构（如 OFA-ProxylessNAS）
# =============================================================================

