void globalISelPatternMatching() {
  // GlobalISel provides the mi_match utility (from MIPatternMatch.h)
  // for pattern matching on G_MIR:
  //
  //   #include "llvm/CodeGen/GlobalISel/MIPatternMatch.h"
  //   using namespace llvm::MIPatternMatch;
  //
  // Pattern matchers:
  //   m_GAdd(m_Reg(LHS), m_Reg(RHS))   -> matches G_ADD
  //   m_GSExt(m_Reg(Src))               -> matches G_SEXT
  //   m_GZExt(m_Reg(Src))               -> matches G_ZEXT
  //   m_GConstInt(m_SpecificInt(42))    -> matches G_CONSTANT with value 42
  //   m_GCst(Cst)                       -> matches G_CONSTANT, captures value
  //   m_GLoad(m_Reg(Ptr))               -> matches G_LOAD
  //   m_GTrunc(m_Reg(Src))              -> matches G_TRUNC
  //
  // Example:
  //   Register PlainLHS, PlainRHS;
  //   if (mi_match(LHSReg, MRI, m_GSExt(m_Reg(PlainLHS))) &&
  //       mi_match(RHSReg, MRI, m_GSExt(m_Reg(PlainRHS)))) {
  //     // Both operands are G_SEXT results
  //     // PlainLHS and PlainRHS hold the source registers
  //   }
  //
  // SDISel added similar utilities (sd_match) since Feb 2024.
}

// ============================================================
// 9. Summary: Selection Pattern Workflow
// ============================================================

void selectionPatternWorkflow() {
  // For each instruction in the selection phase:

  // SDISel:
  //   for each SDNode in DAG:
  //     -> Select(SDNode*)
  //       -> if isMachineOpcode(), skip
  //       -> SelectCode(N)  // TableGen-generated switch
  //         -> tries each pattern for this opcode
  //         -> first match wins
  //         -> ReplaceNode(Old, NewMachineNode)
  //       -> if no match, SDNode remains -> error or later abort

  // FastISel:
  //   for each LLVM IR Instruction in BB:
  //     -> fastSelectInstruction(I)
  //       -> custom switch on I->getOpcode()
  //       -> fallback to selectOperator() (TableGen-generated)
  //       -> if fails, fallback to SDISel (per-BB or full)

  // GlobalISel:
  //   for each MachineInstr in MF:
  //     -> select(MI)
  //       -> selectImpl(MI)  // Imported SDISel patterns
  //       -> switch on MI.getOpcode()  // Manual selection
  //       -> morph MI (setDesc, set operands)
  //       -> constrainSelectedInstRegOperands()
}
