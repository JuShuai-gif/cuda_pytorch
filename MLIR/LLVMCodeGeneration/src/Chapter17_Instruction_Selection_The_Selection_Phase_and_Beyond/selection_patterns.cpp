// 1. TableGen Selection Patterns (conceptual)
// ============================================================

// Patterns are written in .td files using the Pat class.
// They describe: (input_dag) -> (output_dag)

// --- Example .td pattern definitions ---

/*
// Simple pattern: integer addition
def : Pat<(add i16:$src1, i16:$src2),
          (ADD16 $src1, $src2)>;

// Pattern with immediate operand
def : Pat<(add i16:$src, (i16 imm:$imm)),
          (ADD16i $src, imm:$imm)>;

// Pattern with complex matching (calls C++ function)
def : Pat<(add i16:$src1, (i16 (load i16:$addr))),
          (ADD16rm $src1, i16:$addr)>;

// Using PatFrag for reusable fragments
def zextloadi16 : PatFrag<(ops node:$ptr),
                          (i16 (zextloadi8 node:$ptr))>;
def : Pat<(add i16:$src, (i16 (zextloadi8 i16:$addr))),
          (ADD16rm_zext $src, i16:$addr)>;

// Pattern with multiple results
def : Pat<(i32 (anyext (i16 (add i16:$src1, i16:$src2)))),
          (ADD16_widen $src1, $src2)>;  // Produces i32 result
*/

// ============================================================
// 2. Pattern Classes in TableGen
// ============================================================

struct TableGenPatternClasses {
  // Pat: Basic pattern.
  //   (input_pattern) -> (output_pattern)
  //   Input matches IR instructions; output is the target instruction.

  // PatFrag: Reusable pattern fragment.
  //   def zextload_i16 : PatFrag<(ops node:$ptr),
  //                               (i16 (zextloadi8 node:$ptr))>;
  //   Used in other patterns as: (zextload_i16 $addr)

  // PatLeaf: Leaf pattern matching constants.
  //   def immZExt6 : PatLeaf<(imm), [{ return isUInt<6>(N->getZExtValue()); }]>;
  //   Used as: (ADD16i $src, immZExt6:$imm)

  // ComplexPattern: C++ function for complex matching logic.
  //   def addrMode : ComplexPattern<i16, 2, "SelectAddrMode", [frameindex]>;
  //   Parameters: <result_type, num_operands, "C++FunctionName", [properties]>
};

