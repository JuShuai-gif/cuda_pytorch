// 7. Importing SDISel Patterns into GlobalISel
// ============================================================

void importPatternsExample() {
  // GlobalISel can import SDISel's TableGen patterns using GlobalISelEmitter.
  //
  // In CMakeLists.txt:
  //   tablegen(LLVM XXXGenGlobalISel.inc -gen-global-isel
  //            -warn-on-skipped-patterns)
  //
  // The -warn-on-skipped-patterns flag reports which SDISel patterns
  // could not be imported (due to fundamental differences between the
  // two frameworks).
  //
  // In your InstructionSelector:
  //   #include "XXXGenGlobalISel.inc"
  //   bool select(MachineInstr &I) override {
  //     if (selectImpl(I, *CoverageInfo))  // Generated by GlobalISelEmitter
  //       return true;
  //     return selectCustom(I);
  //   }
  //
  // Limitations:
  //   - Not all SDISel patterns can be imported (e.g., complex SDNodeXForm).
  //   - The fallback is manual C++ selection.
  //   - CoverageInfo tracks which patterns were used for statistics.
}

